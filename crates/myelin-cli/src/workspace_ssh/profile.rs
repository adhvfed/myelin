use std::ffi::{OsStr, OsString};
use std::fs;
use std::path::{Path, PathBuf};

use base64::engine::general_purpose::URL_SAFE_NO_PAD;
use base64::Engine as _;
use rand::{rngs::OsRng, RngCore as _};
use serde_json::{json, Value};

use super::access::{known_host_name, WorkspaceSshGrant};
use super::key::ed25519_fingerprint;
use crate::credential_store::write_owner_only_atomic;
use crate::error::CliError;

const MAX_PUBLIC_KEY_BYTES: u64 = 4 * 1024;
const MAX_CONTROL_SOCKET_PATH_BYTES: usize = 80;

pub(super) struct WorkspaceSshProfile {
    alias: String,
    config_path: PathBuf,
    known_hosts_path: PathBuf,
    expires_at: String,
    workspace_id: String,
    workspace_generation: u64,
}

impl WorkspaceSshProfile {
    pub(super) fn install(
        config_root: &Path,
        thread_id: &str,
        identity_path: &Path,
        public_key_path: Option<&Path>,
        grant: WorkspaceSshGrant,
    ) -> Result<Self, CliError> {
        let identity_path = canonical_regular_file(identity_path, "SSH identity")?;
        let public_key_path = match public_key_path {
            Some(path) => canonical_regular_file(path, "SSH public key")?,
            None => canonical_regular_file(
                &sibling_public_key_path(identity_path.as_os_str()),
                "SSH public key",
            )?,
        };
        let public_key = read_public_key(&public_key_path)?;
        let fingerprint = ed25519_fingerprint(&public_key, true)?;
        if fingerprint != grant.access.public_key_fingerprint {
            return Err(CliError::Config(
                "the SSH public key changed while editor access was being authorized".into(),
            ));
        }

        let profiles_directory = config_root.join("workspace-ssh");
        create_private_directory(&profiles_directory)?;
        let profile_directory = profiles_directory.join(thread_id);
        create_private_directory(&profile_directory)?;
        let config_path = profile_directory.join("config");
        let known_hosts_path = profile_directory.join("known_hosts");
        let control_path = fresh_control_path(&profiles_directory)?;
        let alias = format!("myelin-thread-{thread_id}");

        let host_pin = format!(
            "{} {}\n",
            known_host_name(&grant.access.host, grant.access.port),
            grant.access.host_public_key
        );
        write_owner_only_atomic(&known_hosts_path, host_pin.as_bytes())?;

        let config = format!(
            "# Generated by Myelin for workspace {workspace}; refresh after {expires}.\n\
             Host {alias}\n\
               HostName {host}\n\
               Port {port}\n\
               User {user}\n\
               IdentityFile {identity}\n\
               IdentitiesOnly yes\n\
               IdentityAgent none\n\
               PasswordAuthentication no\n\
               KbdInteractiveAuthentication no\n\
               StrictHostKeyChecking yes\n\
               UserKnownHostsFile {known_hosts}\n\
               GlobalKnownHostsFile /dev/null\n\
               UpdateHostKeys no\n\
               ForwardAgent no\n\
               ForwardX11 no\n\
               ClearAllForwardings yes\n\
               PermitLocalCommand no\n\
               ProxyCommand none\n\
               ProxyJump none\n\
               ConnectTimeout 10\n\
               ControlMaster auto\n\
               ControlPersist 5m\n\
               ControlPath {control_path}\n",
            workspace = grant.workspace.id,
            expires = grant.access.expires_at,
            host = grant.access.host,
            port = grant.access.port,
            user = grant.access.username,
            identity = ssh_config_path(&identity_path)?,
            known_hosts = ssh_config_path(&known_hosts_path)?,
            control_path = ssh_config_path(&control_path)?,
        );
        write_owner_only_atomic(&config_path, config.as_bytes())?;

        Ok(Self {
            alias,
            config_path,
            known_hosts_path,
            expires_at: grant.access.expires_at,
            workspace_id: grant.workspace.id,
            workspace_generation: grant.workspace.generation,
        })
    }

    pub(super) fn render(&self, json_output: bool) -> Result<String, CliError> {
        if json_output {
            return serde_json::to_string_pretty(&self.json())
                .map(|encoded| format!("{encoded}\n"))
                .map_err(|error| {
                    CliError::Config(format!("could not render SSH profile: {error}"))
                });
        }
        Ok(format!(
            "Authorized editor SSH profile until {expires}.\n  host: {alias}\n  config: {config}\n  connect: ssh -F {shell_config} {alias}\n  files: select this SSH config and host in an SFTP-capable editor; the workspace opens at /workspace.\n  refresh: rerun this command before reconnecting after expiry.\n",
            expires = self.expires_at,
            alias = self.alias,
            config = self.config_path.display(),
            shell_config = shell_word(&self.config_path)?,
        ))
    }

    fn json(&self) -> Value {
        json!({
            "host_alias": self.alias,
            "config_path": self.config_path,
            "known_hosts_path": self.known_hosts_path,
            "expires_at": self.expires_at,
            "workspace": {
                "id": self.workspace_id,
                "generation": self.workspace_generation,
            },
        })
    }
}

pub(super) fn requested_public_key(
    identity_path: &Path,
    public_key_path: Option<&Path>,
) -> Result<(String, String), CliError> {
    let identity_path = canonical_regular_file(identity_path, "SSH identity")?;
    let path = match public_key_path {
        Some(path) => canonical_regular_file(path, "SSH public key")?,
        None => canonical_regular_file(
            &sibling_public_key_path(identity_path.as_os_str()),
            "SSH public key",
        )?,
    };
    let public_key = read_public_key(&path)?;
    let fingerprint = ed25519_fingerprint(&public_key, true)?;
    Ok((public_key, fingerprint))
}

fn sibling_public_key_path(identity_path: &OsStr) -> PathBuf {
    let mut path = OsString::from(identity_path);
    path.push(".pub");
    PathBuf::from(path)
}

fn canonical_regular_file(path: &Path, description: &str) -> Result<PathBuf, CliError> {
    let canonical = fs::canonicalize(path).map_err(|error| {
        CliError::Config(format!(
            "could not resolve {description} {}: {error}",
            path.display()
        ))
    })?;
    let metadata = fs::metadata(&canonical).map_err(|error| {
        CliError::Config(format!(
            "could not inspect {description} {}: {error}",
            canonical.display()
        ))
    })?;
    if !metadata.is_file() {
        return Err(CliError::Config(format!(
            "{description} {} is not a regular file",
            canonical.display()
        )));
    }
    ssh_config_path(&canonical)?;
    Ok(canonical)
}

fn read_public_key(path: &Path) -> Result<String, CliError> {
    let metadata = fs::metadata(path).map_err(|error| {
        CliError::Config(format!(
            "could not inspect SSH public key {}: {error}",
            path.display()
        ))
    })?;
    if metadata.len() > MAX_PUBLIC_KEY_BYTES {
        return Err(CliError::Config(
            "SSH public key exceeds the 4 KiB limit".into(),
        ));
    }
    let encoded = fs::read(path).map_err(|error| {
        CliError::Config(format!(
            "could not read SSH public key {}: {error}",
            path.display()
        ))
    })?;
    let public_key = String::from_utf8(encoded)
        .map_err(|_| CliError::Config("SSH public key is not UTF-8".into()))?;
    Ok(public_key.trim_end_matches(['\r', '\n']).to_string())
}

fn create_private_directory(path: &Path) -> Result<(), CliError> {
    fs::create_dir_all(path).map_err(|error| {
        CliError::Config(format!(
            "could not create SSH profile directory {}: {error}",
            path.display()
        ))
    })?;
    let metadata = fs::symlink_metadata(path).map_err(|error| {
        CliError::Config(format!(
            "could not inspect SSH profile directory {}: {error}",
            path.display()
        ))
    })?;
    if metadata.file_type().is_symlink() || !metadata.is_dir() {
        return Err(CliError::Config(format!(
            "SSH profile directory {} is not a real directory",
            path.display()
        )));
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt as _;
        fs::set_permissions(path, fs::Permissions::from_mode(0o700)).map_err(|error| {
            CliError::Config(format!(
                "could not protect SSH profile directory {}: {error}",
                path.display()
            ))
        })?;
    }
    Ok(())
}

fn fresh_control_path(directory: &Path) -> Result<PathBuf, CliError> {
    let mut random = [0_u8; 9];
    OsRng.fill_bytes(&mut random);
    let path = directory.join(format!("control-{}", URL_SAFE_NO_PAD.encode(random)));
    let encoded = path.to_str().ok_or_else(|| {
        CliError::Config(format!(
            "SSH control socket path {} is not UTF-8",
            path.display()
        ))
    })?;
    if encoded.len() > MAX_CONTROL_SOCKET_PATH_BYTES {
        return Err(CliError::Config(format!(
            "SSH control socket path is too long; select a shorter Myelin config directory with MYELIN_CONFIG_DIR ({} bytes, maximum {MAX_CONTROL_SOCKET_PATH_BYTES})",
            encoded.len()
        )));
    }
    Ok(path)
}

fn ssh_config_path(path: &Path) -> Result<String, CliError> {
    let value = path.to_str().ok_or_else(|| {
        CliError::Config(format!("SSH config path {} is not UTF-8", path.display()))
    })?;
    if value.chars().any(char::is_control) {
        return Err(CliError::Config(
            "SSH config paths cannot contain control characters".into(),
        ));
    }
    Ok(format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('%', "%%")
    ))
}

fn shell_word(path: &Path) -> Result<String, CliError> {
    let value = path.to_str().ok_or_else(|| {
        CliError::Config(format!("SSH config path {} is not UTF-8", path.display()))
    })?;
    Ok(format!("'{}'", value.replace('\'', "'\\''")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn config_paths_are_quoted_and_percent_tokens_are_inert() {
        assert_eq!(
            ssh_config_path(Path::new("/tmp/a b/%C/quote\"")).unwrap(),
            "\"/tmp/a b/%%C/quote\\\"\""
        );
        assert!(ssh_config_path(Path::new("bad\npath")).is_err());
    }

    #[cfg(unix)]
    #[test]
    fn managed_profile_directories_never_follow_symlinks() {
        use std::os::unix::fs::symlink;

        let root = tempfile::tempdir().unwrap();
        let target = root.path().join("target");
        fs::create_dir(&target).unwrap();
        let link = root.path().join("workspace-ssh");
        symlink(&target, &link).unwrap();
        assert!(create_private_directory(&link).is_err());
    }
}
