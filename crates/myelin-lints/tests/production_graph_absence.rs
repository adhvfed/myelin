#[test]
fn the_production_graph_absence_ratchet_equals_the_committed_baseline() {
    let root = workspace_root();
    let live = live_violations(&root);
    let mut baseline: Vec<(String, String, usize)> = BASELINE
        .iter()
        .map(|(s, p, l)| (s.to_string(), p.to_string(), *l))
        .collect();
    baseline.sort(); // `live` is sorted; sort the manifest so the set-equality compare is order-free.

    // (a) A NEW violation that is NOT in the baseline → a NEW production-graph shortcut was
    //     introduced. FAIL LOUDLY: fix the code (do NOT add it to the baseline — the ratchet only
    //     tightens; a new shortcut must not be normalized into the manifest).
    let new: Vec<&(String, String, usize)> =
        live.iter().filter(|v| !baseline.contains(v)).collect();
    assert!(
        new.is_empty(),
        "NEW production-graph shortcut(s) introduced (loud, never swallowed — fix the code, do NOT \
         add to the baseline; the ratchet can only tighten toward zero):\n{}",
        new.iter()
            .map(|(s, p, l)| format!("  [{s}] {p}:{l}"))
            .collect::<Vec<_>>()
            .join("\n")
    );

    // (b) A baseline entry that NO LONGER fires → it was fixed (or its line moved). FAIL LOUDLY:
    //     remove (or re-pin) its baseline entry — the ratchet must record the tightening (this is
    //     exactly how MR-009/012/013 prove they removed a shortcut: they delete its entry here).
    let fixed: Vec<&(String, String, usize)> =
        baseline.iter().filter(|v| !live.contains(v)).collect();
    assert!(
        fixed.is_empty(),
        "baseline shortcut(s) FIXED or MOVED but still in the manifest (the ratchet tightens — \
         delete the removed entry, or re-pin a moved line):\n{}",
        fixed
            .iter()
            .map(|(s, p, l)| format!("  [{s}] {p}:{l}"))
            .collect::<Vec<_>>()
            .join("\n")
    );

    // Belt-and-braces: equal as sets (the two asserts above already imply this, stated explicitly).
    assert_eq!(
        live, baseline,
        "the live production-graph absence violation set must EQUAL the committed baseline"
    );
}
