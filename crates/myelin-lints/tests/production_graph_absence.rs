//! # The production-graph ABSENCE baseline ratchet (MR-004) — the evidence-integrity skeleton.
//!
//! This test wires the three production-graph absence scanners
//! ([`myelin_lints::production_graph`]) two ways, in the same shape as the twelve architecture
//! lints' `fixture_matrix.rs` + `workspace_clean.rs`:
//!
//!   1. **The fixture matrix** — each scanner's RED fixture produces ≥1 violation (it bites) and
//!      its GREEN fixture produces 0 (it does not over-reject), and each red trips EXACTLY its own
//!      scanner (cross-isolation). This is the fixtures half (deterministic, hermetic).
//!
//!   2. **The baseline ratchet** — the scanners are run over the REAL `crates/*/src` tree and the
//!      violation set is asserted to EQUAL a committed baseline manifest of the CURRENT known
//!      shortcut sites — NOT zero. The real tree VIOLATES all three scanners by design (that is the
//!      whole point: they document the live shortcuts MR-009/MR-012/MR-013 will remove), so these
//!      three are deliberately NOT in `all_twelve()` / the `workspace_clean` zero-violation gate
//!      (adding them there would turn the build red). The ratchet can only TIGHTEN toward zero: it
//!      FAILS LOUDLY if (a) a NEW violation appears anywhere in scope, or (b) a baseline entry is
//!      fixed/moved but not removed from the manifest. That is the mechanism by which MR-009/012/013
//!      prove they actually removed the shortcut (EI-01 §5 — an uncommitted gate is no gate).
//!
//! ## Scope of each scanner's gate (documented, LOUD — never a silent skip; EI-01 §4)
//! Like `workspace_clean.rs`'s named exclusions, each scanner's WORKSPACE gate is scoped to where
//! its census-named shortcuts live, and the scope is named here, not hidden:
//!   - `no-structural-crypto-in-prod` → ALL crates. The `Structural*` mock-crypto types are few and
//!     the scanner is precise (construction-only, `#[cfg(test)]`-excluded), so a workspace-wide gate
//!     is clean and catches any prod construction wherever it appears.
